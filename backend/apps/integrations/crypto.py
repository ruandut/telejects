"""Encrypting a connection's secrets at rest.

The keys come from INTEGRATIONS_ENCRYPTION_KEYS in .env (comma-separated Fernet keys, newest
first), generated by scripts/init_env.sh. Encrypting uses the first; decrypting tries them all,
so a key can be rotated by putting a new one in front and re-saving the connections.
"""

import json
from functools import cache

from cryptography.fernet import Fernet, InvalidToken, MultiFernet
from django.conf import settings
from django.core.exceptions import ImproperlyConfigured


@cache
def _fernet() -> MultiFernet:
    keys = [k.strip() for k in settings.INTEGRATIONS_ENCRYPTION_KEYS if k.strip()]
    if not keys:
        raise ImproperlyConfigured("INTEGRATIONS_ENCRYPTION_KEYS is empty; run make env.")
    return MultiFernet([Fernet(k.encode()) for k in keys])


def encrypt(values: dict) -> str:
    return _fernet().encrypt(json.dumps(values).encode()).decode()


def decrypt(token: str) -> dict:
    if not token:
        return {}
    try:
        return json.loads(_fernet().decrypt(token.encode()))
    except InvalidToken:
        raise ImproperlyConfigured(
            "A connection's secrets can't be decrypted with INTEGRATIONS_ENCRYPTION_KEYS."
        ) from None
